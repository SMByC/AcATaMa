def get_plugin_version(version_string):
    if isinstance(version_string, (int, float)):
        version_string = str(version_string)

    # handle non-numeric version strings like "dev"
    if not re.sub(r"\D", "", version_string):
        return 999999

    version = "".join(["{:0>2}".format(re.sub(r"\D", "", x)) for x in version_string.split(".")])

    if len(version) == 4:
        version += "00"

    return int(version)


def mask(input_list, boolean_mask):
    """Apply boolean mask to input list

    Args:
        input_list (list): Input list for apply mask
        boolean_mask (list): The boolean mask list

    Examples:
        >>> mask(["A", "B", "C", "D"], [1, 0, 1, 0])
        ['A', 'C']
    """
    return [i for i, b in zip(input_list, boolean_mask, strict=True) if b]


