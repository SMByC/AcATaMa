# compute pixels count by pixel unique values

storage_pixel_count_by_pixel_values = {}  # storage the pixel/values computed by layer, band and nodata
# keys of the storage counted in the image, with all its pixel values; the counts restored from a
# configuration file only have the pixel values of the symbology
complete_pixel_counts = set()
# the data of the layer of each key of the storage, the counts are not used if it changes
pixel_counts_layer_data = {}


# the GDAL drivers whose pixel values are all in the files that they list (for the VRT, also the ones of the
# datasets that it references), so their values only change if the modification of those files changes; the data
# of the other datasets (databases, web services, Zarr, GeoPackage, tile indexes...) can change without it
CACHEABLE_DRIVERS = {
    "GTIFF",
    "VRT",
    "HFA",
    "ENVI",
    "EHDR",
    "AAIGRID",
    "PNG",
    "JPEG",
    "JP2OPENJPEG",
    "GIF",
    "BMP",
    "RST",
    "SAGA",
}


# the sources of a VRT whose pixel values only depend on the source datasets and on the VRT itself
STATIC_VRT_SOURCES = {"SimpleSource", "ComplexSource", "AveragedSource", "KernelFilteredSource", "NoDataFromMaskSource"}


def get_vrt_sources(dataset, path):
    """The datasets referenced by a VRT, also by its inline VRTs, from its XML serialized by GDAL (the file list
    of GDAL omits the inline VRTs, and the sources that are not files in its versions before 3.8). None if the XML
    can't be read, or if the VRT is not static: a VRT subclass (warped, pansharpened, processed, derived bands...)
    or other sources, whose pixel values can depend on other files (e.g. in the arguments of the processing) or
    code"""
    try:
        vrt_xml = ET.fromstring(dataset.GetMetadata("xml:VRT")[0])  # nosec B314 - XML serialized in-process by GDAL
    except Exception:
        return None
    sources = []
    for element in vrt_xml.iter():
        if element.tag in ("VRTDataset", "VRTRasterBand") and element.get("subClass"):
            return None
        if element.tag.endswith("Source") and element.tag not in STATIC_VRT_SOURCES:
            return None
        if element.tag == "SourceFilename" and element.text and element.text.strip():
            source = element.text.strip()
            relative_to_vrt = element.get("relativeToVRT") == "1"
            sources.append(os.path.join(os.path.dirname(path), source) if relative_to_vrt else source)
    return sources


def get_dataset_files(source):
    """All the files of a GDAL dataset, also the ones of the datasets that it references (e.g. VRT of VRTs) and
    its auxiliary files (that can have its georeferencing). None if the dataset can't be opened or if its pixel
    values are not known to be only in these files (not a CACHEABLE_DRIVERS dataset, in a virtual file system, or
    referencing a dataset that is not a file, e.g. a database)"""
    files, to_open = set(), [source]
    gdal.PushErrorHandler("CPLQuietErrorHandler")
    try:
        while to_open:
            path = to_open.pop()
            if path.lower().startswith("/vsi") or "://" in path:
                return None
            try:
                dataset = gdal.Open(path, gdal.GA_ReadOnly)
            except Exception:
                dataset = None
            if dataset is None:
                if path == source:
                    return None
                # not a dataset (an auxiliary file)
                continue
            driver = dataset.GetDriver().ShortName.upper()
            if driver not in CACHEABLE_DRIVERS:
                return None
            file_list = dataset.GetFileList() or []
            if driver == "VRT":
                vrt_sources = get_vrt_sources(dataset, path)
                if vrt_sources is None:
                    return None
                file_list += vrt_sources
            dataset = None
            new_files = set(file_list) - files
            if not all(os.path.exists(file_path) for file_path in new_files):
                return None
            files |= new_files
            to_open += [file_path for file_path in new_files if file_path != path]
    finally:
        gdal.PopErrorHandler()
    return files


def get_layer_data(layer, band):
    """Data of a band of a layer that changes when its pixel values, as read by the provider, change: the source,
    the modification of its files (also the ones referenced, e.g. by a VRT) and the no data of the provider. None
    if it can't be known (no files), then the data computed from the layer can't be reused"""
    source = get_source_from(layer)
    files = []
    for file_path in sorted(get_dataset_files(source) or []):
        try:
            file_status = os.stat(file_path)
        except OSError:
            return None
        # the status change time also changes when a file is replaced by a copy with the same modification time
        files.append((file_path, file_status.st_mtime_ns, file_status.st_ctime_ns, file_status.st_size))
    if not files:
        return None
    provider = layer.dataProvider()
    nodata = (
        provider.sourceHasNoDataValue(band),
        provider.useSourceNoDataValue(band),
        provider.sourceNoDataValue(band),
        [(no_data_range.min(), no_data_range.max()) for no_data_range in provider.userNoDataValues(band)],
    )
    # as text, NaN values are equal
    return source, tuple(files), repr(nodata)


def set_pixel_counts(layer, band, nodata, pixel_counts, complete=True):
    """Store the pixel counts by pixel value of the layer, band and nodata"""
    storage_pixel_count_by_pixel_values[(layer, band, nodata)] = pixel_counts
    pixel_counts_layer_data[(layer, band, nodata)] = get_layer_data(layer, band)
    if complete:
        complete_pixel_counts.add((layer, band, nodata))
    else:
        complete_pixel_counts.discard((layer, band, nodata))


def clear_pixel_counts(layer, band, nodata):
    """Delete the stored pixel counts of the layer, band and nodata, so they are counted again"""
    storage_pixel_count_by_pixel_values.pop((layer, band, nodata), None)
    pixel_counts_layer_data.pop((layer, band, nodata), None)
    complete_pixel_counts.discard((layer, band, nodata))


def get_pixel_count_by_pixel_values(layer, band, pixel_values=None, nodata=None, complete=False):
    """Meta function to compute the pixel count by pixel values

    Args:
        complete: require the counts of all the pixel values in the image, not only the ones of the symbology
    """

    # check if it was already computed (with the current data of the layer), then return it
    key = (layer, band, nodata)
    if (
        key in storage_pixel_count_by_pixel_values
        and (not complete or key in complete_pixel_counts)
        and pixel_counts_layer_data.get(key) is not None
        and pixel_counts_layer_data[key] == get_layer_data(layer, band)
    ):
        return storage_pixel_count_by_pixel_values[key]

    # Try parallel processing with dask when available
    if dask_is_available():
        pixel_count = get_pixel_count_by_pixel_values_parallel(layer, band, pixel_values, nodata)
        if pixel_count is not None:
            return pixel_count

    # Try QGIS native method
    pixel_count = get_pixel_count_by_pixel_values_qgis_native(layer, band, pixel_values, nodata)
    if pixel_count is not None:
        return pixel_count

    # Fallback to sequential processing
    return get_pixel_count_by_pixel_values_sequential(layer, band, pixel_values, nodata)


def dask_is_available():
    return importlib.util.find_spec("dask") is not None


