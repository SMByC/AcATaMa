@wait_process
def get_pixel_count_by_pixel_values_sequential(layer, band, pixel_values=None, nodata=None):
    """Get the total pixel count for each pixel values reading the image by chunks, the counts include
    all the pixel values in the image, also the ones that are not in the symbology"""
    if pixel_values is None:
        pixel_values = get_unique_pixel_values(layer, band, nodata)

    progress = QProgressDialog(
        "AcATaMa is counting the number of pixels for each thematic value.\n"
        "Depending on the size of the image, it would take a few minutes.",
        None,
        0,
        100,
    )
    progress.setWindowTitle("AcATaMa - Counting pixels by values...")
    progress.setWindowModality(Qt.WindowModality.WindowModal)
    progress.setValue(0)
    progress.show()
    QApplication.processEvents()

    # Initialize counts with 0 for all pixel values from symbology, without the nodata
    pairing_values_and_counts = dict.fromkeys([v for v in pixel_values if nodata is None or v != nodata], 0)

    data_in_chunks = get_image_chunks(layer, band)
    for num_chunk, chunk in enumerate(data_in_chunks):
        for value, count in pixel_count_in_chunk(*chunk).items():
            if nodata is not None and value == nodata:
                continue
            pairing_values_and_counts[value] = pairing_values_and_counts.get(value, 0) + count
        progress.setValue(int((num_chunk + 1) / len(data_in_chunks) * 100))
        QApplication.processEvents()

    progress.close()
    set_pixel_counts(layer, band, nodata, pairing_values_and_counts)
    return pairing_values_and_counts


