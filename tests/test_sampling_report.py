from AcATaMa.gui.sampling_report import SamplingReport
from AcATaMa.utils.others_utils import get_nodata_format


def test_restored_sampling_report(plugin, restore_config_file):
    """A report saved by a previous version (without the new fields) is rendered with the design warnings"""
    restore_config_file(pytest.tests_data_dir / "test_systematic_by_pixels_with_offset.yaml")
    sampling_report = SamplingReport.instances[plugin.dockwidget.QCBox_SamplingFile.currentLayer()]

    html = sampling_report.get_html()
    assert "Distribution of samples on the thematic map" in html
    assert "Neighbor aggregation restricts the population!" in html
    assert "Draws per Offset Area" not in html
    # the previous versions repeated the draws in the offset areas
    assert "generated by a previous version of AcATaMa" in html

    csv_rows = sampling_report._build_csv_rows()
    assert ["Warning: Neighbor aggregation restricts the population!"] in csv_rows

    # the consequences of the neighbor aggregation for the estimator of the analysis
    neighbor_aggregation = "Neighbor aggregation restricts the population!"
    simple = dict(sampling_report.get_design_warnings(estimators.SIMPLE))[neighbor_aggregation]
    assert "the area estimates, which use the total area of the whole map, are not valid" in simple
    stratified = dict(sampling_report.get_design_warnings(estimators.STRATIFIED))[neighbor_aggregation]
    assert "the user's accuracies refer only to that part of the map" in stratified
    assert "neither for the whole map nor for that part" in stratified

    # with a fixed initial inset the offset areas (spacing of 5 pixels) must tile the map
    general = sampling_report.report["general"]
    general["initial_inset_mode"] = "Fixed"
    assert "Offset areas do not tile the map!" in sampling_report.get_html()
    general["max_xy_offset"] = "2.5 pixels"
    assert "Offset areas do not tile the map!" not in sampling_report.get_html()
    general["max_xy_offset"] = "0 pixels"
    assert "Non-random systematic grid!" in sampling_report.get_html()


def test_stratified_sampling_report(plugin, restore_config_file, tmp_path):
    restore_config_file(pytest.tests_data_dir / "test_sampling.yaml")
    sampling_design = plugin.dockwidget.sampling_design_window
    thematic_map = Map(
        file_selected_combo_box=plugin.dockwidget.QCBox_ThematicMap,
        band=int(plugin.dockwidget.QCBox_band_ThematicMap.currentText()),
        nodata=get_nodata_format(plugin.dockwidget.nodata_ThematicMap.text()),
    )
    sampling_map = Map(
        file_selected_combo_box=sampling_design.QCBox_SamplingMap_StraRS,
        band=int(sampling_design.QCBox_band_SamplingMap_StraRS.currentText()),
        nodata=get_nodata_format(sampling_design.nodata_SamplingMap_StraRS.text()),
    )
    classes = [int(sampling_design.QTableW_StraRS.item(row, 0).text()) for row in range(3)]
    # more samples than pixels in the second stratum, so not all the desired samples can be generated
    total_of_samples = [5, 10**6, 0]
    output_file = tmp_path / "stratified.gpkg"
    sampling = Sampling(
        "stratified",
        thematic_map,
        sampling_map=sampling_map,
        sampling_method="fixed values",
        output_file=str(output_file),
    )
    task = type(
        "QgsTask",
        (object,),
        {"setProgress": lambda x: None, "isCanceled": lambda: len(sampling.points) >= 25},
    )
    sampling_conf = {
        "sampling_type": "stratified",
        "total_of_samples": total_of_samples,
        "min_distance": 0,
        "classes_selected": classes,
        "neighbor_aggregation": None,
        "random_seed": 4321,
        "random_seed_by_user": False,
    }
    sampling.generate_sampling_points(task, sampling_conf)
    sampling_layer = QgsVectorLayer(str(output_file), "stratified", "ogr")
    # owned by the project, a layer destroyed at the exit of the interpreter crashes it
    QgsProject.instance().addMapLayer(sampling_layer)

    sampling_report = SamplingReport(sampling_layer, sampling, sampling_conf)
    strata_table, desired, actual = sampling_report.get_strata_samples()

    # matched by pixel value of the strata
    by_value = dict(zip(strata_table["pix_val"], zip(desired, actual, strict=True), strict=True))
    assert by_value[classes[0]] == (5, sampling.samples_in_strata[0])
    assert by_value[classes[1]] == (10**6, sampling.samples_in_strata[1])
    assert by_value[classes[2]] == (0, 0)
    assert sampling_report.report["general"]["random_seed"] == "4321 (automatic)"
    html = sampling_report.get_html()
    assert "Desired/actual sample count mismatch" in html
    assert "<td>4321 (automatic)</td>" in html
    # the band of the thematic map of the sampling, to show it in the warnings of the analysis
    general = sampling_report.report["general"]
    assert general["thematic_map_band"] == thematic_map.band

    # the minimum distance makes the inclusion probabilities unknown (Stehman and Foody, 2019, Sec. 2.4)
    assert "Minimum distance between samples" not in dict(sampling_report.get_design_warnings())
    general["min_distance"] = "30 meters"
    assert "not a probability sample" in dict(sampling_report.get_design_warnings())["Minimum distance between samples"]
